// build.js — Ahead-of-time JSX → JS compiler.
//
// ════════════════════════════════════════════════════════════════════════════
// WHY THIS EXISTS
// ─────────────────────────────────────────────────────────────────────────────
// The site originally shipped raw .jsx and transpiled it IN THE BROWSER with
// babel-standalone (~3 MB script + a multi-second main-thread transpile on
// every page load — brutal on weak devices).
//
// This script does that transpile ONCE, offline. It reads every .jsx under
// src/components/, runs Babel's React preset, and writes a plain .js sibling.
// index.html then loads the compiled .js as ordinary <script> — no babel,
// no in-browser compile.
//
// USAGE
// ─────────────────────────────────────────────────────────────────────────────
//   node build.js
//
// Run this after editing ANY .jsx file. The .jsx files remain the source of
// truth; the .js files are generated artifacts.
//
// IMPLEMENTATION NOTES
// ─────────────────────────────────────────────────────────────────────────────
// We reuse the babel-standalone bundle already vendored in vendor/babel.min.js
// rather than adding an npm dependency. Loaded in a Node CommonJS context it
// exposes `Babel.transform`. The "react" preset converts JSX → React.create-
// Element; no module transform is applied because the components are plain
// browser scripts that share globals (window.*), not ES modules.
// ════════════════════════════════════════════════════════════════════════════

"use strict";

const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const lightningcss = require("lightningcss");
const validateSite = require("./scripts/validate-site.js").validate;

// ── Configuration ──────────────────────────────────────────────────────────
const COMPONENTS_DIR = path.join(__dirname, "src", "components");
const BABEL_BUNDLE = path.join(__dirname, "vendor", "babel.min.js");
// JSX entry files, in load order. Order matters: later files depend on
// globals defined by earlier ones.
const JSX_FILES = [
  "tweaks-panel.jsx",
  "components-1.jsx",
  "components-2.jsx",
  "app.jsx",
];
// Authoring remains split by responsibility, while production receives one
// blocking stylesheet in the exact same cascade order. This cuts six network
// requests and minifies without asking contributors to edit generated CSS.
const STYLE_SOURCES = [
  "fonts.css",
  "styles.css",
  "sections.css",
  "cursor.css",
  "cv-doc.css",
  "features.css",
  "art-direction.css",
  "release-polish.css",
  "release-proof.css",
];
const STYLES_DIR = path.join(__dirname, "src", "styles");
const STYLE_BUNDLE = "app.bundle.min.css";
// Babel preset configuration. "react" → JSX transform only.
// Generated component scripts are shipped directly, so whitespace/comments
// are deployment bytes and parser work. Keep authored JSX readable and emit a
// compact deterministic classic-script representation.
const BABEL_OPTIONS = { presets: ["react"], compact: true, comments: false };
// Banner prepended to every generated file so it's never mistaken for source.
const GENERATED_BANNER =
  "/* AUTO-GENERATED by build.js from $SRC — DO NOT EDIT.\n" +
  "   Edit the .jsx source and re-run `node build.js`. */\n";

const RETRYABLE_WRITE_CODES = new Set(["EACCES", "EBUSY", "EPERM", "UNKNOWN"]);
const WRITE_RETRY_DELAYS_MS = [20, 40, 80, 120, 180, 260];

function sleepSync(ms) {
  // Builds are synchronous by design. Atomics.wait avoids a CPU-burning busy
  // loop while Windows Defender/indexers release a short-lived file handle.
  const signal = new Int32Array(new SharedArrayBuffer(4));
  Atomics.wait(signal, 0, 0, ms);
}

function normalizeLf(value) {
  // Generated artifacts are deployed from Linux but are also built on Windows.
  // Canonical LF bytes keep CSP hashes and committed output platform-neutral.
  return String(value).replace(/\r\n?/g, "\n");
}

function writeUtf8IfChanged(filePath, content) {
  const next = normalizeLf(content);
  try {
    // Do not rewrite byte-identical artifacts. Apart from preserving mtimes,
    // this makes immediate repeated builds immune to transient Windows locks.
    if (fs.readFileSync(filePath, "utf8") === next) return false;
  } catch (error) {
    if (error && error.code !== "ENOENT" && !RETRYABLE_WRITE_CODES.has(error.code)) throw error;
  }

  let lastError = null;
  for (let attempt = 0; attempt <= WRITE_RETRY_DELAYS_MS.length; attempt += 1) {
    try {
      fs.writeFileSync(filePath, next, "utf8");
      return true;
    } catch (error) {
      lastError = error;
      if (!error || !RETRYABLE_WRITE_CODES.has(error.code) || attempt === WRITE_RETRY_DELAYS_MS.length) {
        throw error;
      }
      sleepSync(WRITE_RETRY_DELAYS_MS[attempt]);
    }
  }
  throw lastError;
}

function loadBabel() {
  // babel-standalone UMD: in a CommonJS context it assigns module.exports.
  // require() returns the Babel object directly.
  const babel = require(BABEL_BUNDLE);
  if (!babel || typeof babel.transform !== "function") {
    throw new Error("babel-standalone did not expose transform()");
  }
  return babel;
}

function compileFile(babel, jsxName) {
  const srcPath = path.join(COMPONENTS_DIR, jsxName);
  if (!fs.existsSync(srcPath)) {
    throw new Error("source not found: " + srcPath);
  }
  const source = fs.readFileSync(srcPath, "utf8");
  const result = babel.transform(source, BABEL_OPTIONS);
  if (!result || typeof result.code !== "string") {
    throw new Error("transform produced no code for " + jsxName);
  }
  const outName = jsxName.replace(/\.jsx$/, ".js");
  const outPath = path.join(COMPONENTS_DIR, outName);
  const banner = GENERATED_BANNER.replace("$SRC", jsxName);
  writeUtf8IfChanged(outPath, banner + result.code);
  return { outName: outName, bytes: Buffer.byteLength(result.code, "utf8") };
}

function buildStyleBundle() {
  const source = STYLE_SOURCES.map(function readStyle(name) {
    const filePath = path.join(STYLES_DIR, name);
    if (!fs.existsSync(filePath)) throw new Error("style source not found: " + filePath);
    return "/* source: " + name + " */\n" + normalizeLf(fs.readFileSync(filePath, "utf8"));
  }).join("\n");
  const result = lightningcss.transform({
    filename: STYLE_BUNDLE,
    code: Buffer.from(source, "utf8"),
    minify: true,
    sourceMap: false,
  });
  if (!result || !result.code || !result.code.length) {
    throw new Error("Lightning CSS produced an empty style bundle");
  }
  const banner = "/*! AUTO-GENERATED by build.js from src/styles/*.css — DO NOT EDIT. */\n";
  const output = banner + result.code.toString("utf8") + "\n";
  writeUtf8IfChanged(path.join(STYLES_DIR, STYLE_BUNDLE), output);
  const sourceBytes = Buffer.byteLength(source, "utf8");
  const outputBytes = Buffer.byteLength(output, "utf8");
  process.stdout.write(
    "[build] styles -> src/styles/" + STYLE_BUNDLE + "  (" + outputBytes +
    " bytes; " + Math.round((1 - outputBytes / sourceBytes) * 100) + "% smaller)\n"
  );
  return outputBytes;
}

// ── Product landings ────────────────────────────────────────────────────────
// Generate a static /projects/<slug>/index.html for each product that a visitor
// can't see live (they used to link straight to a GitHub card). Content +
// template come from src/projects/{landings-data,render}.js — the SAME render()
// the page loads client-side, so the baked HTML and the language switcher never
// drift. Real files → clean shareable URLs, own <title>/OG, indexable, instant.
const SITE_BASE = "https://samandarmansurkhodjaev2713.github.io/CV-Samandar/";

function scriptHash(source) {
  return "'sha256-" + crypto.createHash("sha256").update(normalizeLf(source), "utf8").digest("base64") + "'";
}

function contentSecurityPolicy(inlineScripts) {
  const hashes = (inlineScripts || []).map(scriptHash).join(" ");
  return [
    "default-src 'self'",
    "script-src 'self'" + (hashes ? " " + hashes : ""),
    "style-src 'self'",
    "style-src-elem 'self'",
    "style-src-attr 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    "connect-src 'self' https://api.github.com",
    "media-src 'self'",
    "worker-src 'self' blob:",
    "object-src 'none'",
    "frame-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
  ].join("; ");
}

function refreshMainCsp() {
  const indexPath = path.join(__dirname, "index.html");
  let source = normalizeLf(fs.readFileSync(indexPath, "utf8"));
  const inlineScripts = [];
  const inlinePattern = /<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi;
  let match;
  while ((match = inlinePattern.exec(source))) inlineScripts.push(match[1]);
  const meta = '<meta http-equiv="Content-Security-Policy" content="' +
    htmlAttr(contentSecurityPolicy(inlineScripts)) + '">';
  const existing = /<meta\s+http-equiv=["']Content-Security-Policy["'][^>]*>/i;
  if (existing.test(source)) {
    source = source.replace(existing, meta);
  } else {
    source = source.replace(
      /(<meta\s+name=["']viewport["'][^>]*>)/i,
      "$1\n  " + meta
    );
  }
  writeUtf8IfChanged(indexPath, source);
  process.stdout.write("[build] CSP -> index.html (" + inlineScripts.length + " hashed inline data block(s))\n");
  return inlineScripts.length;
}

function readLandingVersion() {
  try {
    const idx = fs.readFileSync(path.join(__dirname, "index.html"), "utf8");
    const m = idx.match(/\?v=(\d+)/);
    return m ? m[1] : "";
  } catch (e) { return ""; }
}

function htmlAttr(s) {
  return String(s == null ? "" : s)
    .replace(/&/g, "&amp;").replace(/"/g, "&quot;")
    .replace(/</g, "&lt;").replace(/>/g, "&gt;");
}


function buildLandings() {
  const dataPath = path.join(__dirname, "src", "projects", "landings-data.js");
  const renderPath = path.join(__dirname, "src", "projects", "render.js");
  if (!fs.existsSync(dataPath) || !fs.existsSync(renderPath)) return 0;
  // Fresh load so a `node build.js` re-run picks up edits within one process.
  delete require.cache[require.resolve(dataPath)];
  delete require.cache[require.resolve(renderPath)];
  const LANDINGS = require(dataPath);
  const R = require(renderPath);
  const version = readLandingVersion();
  const slugs = Object.keys(LANDINGS);
  slugs.forEach(function (slug) {
    const p = LANDINGS[slug];
    const dir = path.join(__dirname, "projects", slug);
    fs.mkdirSync(dir, { recursive: true });
    writeUtf8IfChanged(path.join(dir, "index.html"), renderLandingPage(p, R, version, "ru", "../../"));
    ["en", "uz"].forEach(function buildLocale(lang) {
      const localeDir = path.join(dir, lang);
      fs.mkdirSync(localeDir, { recursive: true });
      writeUtf8IfChanged(path.join(localeDir, "index.html"), renderLandingPage(p, R, version, lang, "../../../"));
    });
    process.stdout.write("[build] landing -> projects/" + slug + "/ (ru/en/uz)\n");
  });
  return slugs.length * 3;
}

function buildSitemap() {
  const registryPath = path.join(__dirname, "src", "content", "product-registry.js");
  delete require.cache[require.resolve(registryPath)];
  const registry = require(registryPath);
  const urls = [SITE_BASE];
  registry
    .filter(function (product) { return product.presentation === "case"; })
    .sort(function (a, b) { return a.featuredRank - b.featuredRank; })
    .forEach(function addCaseLocales(product) {
      urls.push(SITE_BASE + product.casePage);
      urls.push(SITE_BASE + product.casePage + "en/");
      urls.push(SITE_BASE + product.casePage + "uz/");
    });
  const xml = [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ].concat(urls.map(function (url) {
    return "  <url><loc>" + url.replace(/&/g, "&amp;").replace(/</g, "&lt;") + "</loc></url>";
  }), ["</urlset>", ""]).join("\n");
  writeUtf8IfChanged(path.join(__dirname, "sitemap.xml"), xml);
  process.stdout.write("[build] sitemap -> sitemap.xml (" + urls.length + " URLs)\n");
  return urls.length;
}

function main() {
  try {
    const contract = validateSite({ generated: false });
    process.stdout.write(
      "[build] contract OK — " + contract.products + " products, " +
      contract.cases + " case routes, " + contract.locales + " locales\n"
    );
  } catch (err) {
    process.stderr.write("[build] contract FAILED: " + err.message + "\n");
    process.exit(1);
    return;
  }

  let babel;
  try {
    babel = loadBabel();
  } catch (err) {
    process.stderr.write("[build] failed to load Babel: " + err.message + "\n");
    process.exit(1);
    return;
  }

  let totalBytes = 0;
  for (let i = 0; i < JSX_FILES.length; i++) {
    const jsxName = JSX_FILES[i];
    try {
      const info = compileFile(babel, jsxName);
      totalBytes += info.bytes;
      process.stdout.write("[build] " + jsxName + " -> " + info.outName + "  (" + info.bytes + " bytes)\n");
    } catch (err) {
      process.stderr.write("[build] FAILED on " + jsxName + ": " + err.message + "\n");
      process.exit(1);
      return;
    }
  }
  try {
    buildStyleBundle();
  } catch (err) {
    process.stderr.write("[build] styles FAILED: " + err.message + "\n");
    process.exit(1);
    return;
  }
  let landingCount = 0;
  let sitemapCount = 0;
  try {
    refreshMainCsp();
    landingCount = buildLandings();
    sitemapCount = buildSitemap();
    validateSite({ generated: true });
  } catch (err) {
    process.stderr.write("[build] landings FAILED: " + err.message + "\n");
    process.exit(1);
    return;
  }
  process.stdout.write(
    "[build] done — " + JSX_FILES.length + " files, " + totalBytes +
    " bytes total; " + landingCount + " landing(s); " + sitemapCount + " sitemap URL(s).\n"
  );
}

main();
